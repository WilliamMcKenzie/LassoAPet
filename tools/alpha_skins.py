LINE = re.compile(r'^(\s*\{ name = "([^"]+)".*color = Color3\.fromRGB\()([0-9, ]+)(\).*)$')


def skin(kind):
    base, swap, glow = SKINS[kind]
    src = os.path.join(ROOT, "src", "shared", base + ".luau")
    out = []
    for line in open(src).read().split("\n"):
        m = LINE.match(line)
        if m:
            head, name, rgb, tail = m.groups()
            new = swap.get(rgb)
            lit = False
            for names, color in glow:
                if any(n in name for n in names):
                    lit = True
                    if color:
                        new = color
                    break
            if new:
                rgb = ", ".join(str(c) for c in new)
            if lit and "neon = true" not in tail:
                tail = tail.replace(") }", "), neon = true }", 1)
            line = head + rgb + tail
        out.append(line)
    text = "\n".join(out)
    text = re.sub(r"^-- GENERATED by .*?\n-- change the .bbmodel in Blockbench and regenerate.\n",
                  f"-- GENERATED by tools/alpha_skins.py from {base}.luau ({kind}). Don't edit by hand:\n"
                  f"-- change SKINS there (or the base) and regenerate.\n", text, count=1, flags=re.S)
    return text


PART = re.compile(r'name = "([^"]+)".*?class = "(\w+)", size = Vector3\.new\(([^)]*)\), cframe = CFrame\.new\(([^)]*)\), '
                  r'color = Color3\.fromRGB\(([^)]*)\)(.*)')


def parts_of(text):
    parts = []
    for m in PART.finditer(text):
        name, cls, size, cf, rgb, rest = m.groups()
        v = [float(x) for x in cf.split(",")]
        M = np.eye(4)
        M[:3, 3] = v[:3]
        M[:3, :3] = np.array(v[3:]).reshape(3, 3)
        shape = {"WedgePart": "Wedge", "CornerWedgePart": "CornerWedge"}.get(cls, "Block")
        p = Part(name, [float(x) for x in size.split(",")], M, tuple(int(x) for x in rgb.split(",")), shape)
        p.neon = "neon = true" in rest.split("}")[0]
        parts.append(p)
    return parts


def main(args):
    for kind in SKINS:
        with open(os.path.join(ANIMALS, kind + "Model.luau"), "w") as f:
            f.write(skin(kind))
        print(kind)
    if "--render" in args:
        kinds = [a for a in args if a in SKINS] or list(SKINS)
        tiles = []
        for kind in kinds:
            base = SKINS[kind][0]
            for text, label in ((open(os.path.join(ROOT, "src", "shared", base + ".luau")).read(), base.split("/")[1][:-5]),
                                (skin(kind), kind)):
                ps = parts_of(text)
                pts = np.array([p.cf[:3, 3] for p in ps])
                c = (pts.min(0) + pts.max(0)) / 2
                r = max(np.ptp(pts, 0)) + 4
                im = render(ps, eye=tuple(c + np.array([-1.0, 0.6, -1.1]) * r * 0.75), target=tuple(c), W=420, H=420, fov=40)
                tiles.append(A.label(im, [label]))
        sheet = Image.new("RGB", (420 * 2, 460 * len(kinds)), "white")
        for i, t in enumerate(tiles):
            sheet.paste(t, (420 * (i % 2), 460 * (i // 2)))
        sheet.save(args[args.index("--render") + 1])


if __name__ == "__main__":
    main(sys.argv[1:])
